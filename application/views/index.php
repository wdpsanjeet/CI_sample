    <script>
    $(document).ready(function () {
    $(document).on('submit', '#subscribe-form', function (event) {
        event.preventDefault();
        $('.text-light').html('');
        var url = $(this).attr('action');
        
        var data = new FormData($(this)[0]);
        $.ajax({
            url: url,
            type: 'POST',
            dataType: 'json',
            processData: false,
            contentType: false,
            data: data,
            success: function (resp) {
                if (resp.status === 200) {
                    if (resp.message) {
                        $('#subscribe-form').closest('.container').find('.alert-success').html(resp.message).show();
                        $('#subscribe-form').trigger("reset");
                    }
                } else {
                    $.each(resp.message, function (key, val) {
                        $('#subscribe-form').find('[name="' + key + '"]').closest('.container').find('.text-light').html(val);
                    });
                }
            }
        }).fail(function () {
        });
    });
    });
    
    </script>
